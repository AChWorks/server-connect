//go:build linux

package sc

// These observations cover the currently registered IPv4/IPv6 xtables
// policies, not ARP, bridge/ebtables, tc, BPF or a reservation against another
// privileged writer. No legacy table is adopted, flushed or restored.
import (
	"bytes"
	"strconv"
	"strings"
	"time"
)

type hostLegacyPacketSnapshot struct {
	raw  [2][]byte
	nat4 []byte
}

func hostLegacyPolicyUnverified() error {
	return Fault("foreign_legacy_policy_unverified", "complete inert IPv4/IPv6 legacy packet policy cannot be verified")
}

func hostLegacyBuiltinChains(table string) []string {
	switch table {
	case "raw":
		return []string{"PREROUTING", "OUTPUT"}
	case "mangle":
		return []string{"PREROUTING", "INPUT", "FORWARD", "OUTPUT", "POSTROUTING"}
	case "nat":
		return []string{"PREROUTING", "INPUT", "OUTPUT", "POSTROUTING"}
	case "filter", "security":
		return []string{"INPUT", "FORWARD", "OUTPUT"}
	}
	return nil
}

func hostLegacyRegisteredTables(raw []byte) (map[string]bool, error) {
	names := map[string]bool{}
	if len(raw) == 0 {
		return names, nil // Only after a successful, independently bounded proc read.
	}
	if len(raw) > 256 || raw[len(raw)-1] != '\n' || bytes.IndexByte(raw, 0) >= 0 {
		return nil, hostLegacyPolicyUnverified()
	}
	for _, name := range strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n") {
		if names[name] || hostLegacyBuiltinChains(name) == nil {
			return nil, hostLegacyPolicyUnverified()
		}
		names[name] = true
	}
	return names, nil
}

func hostLegacySaveTime(line, prefix string) bool {
	value, found := strings.CutPrefix(line, prefix)
	if !found || len(value) > 32 {
		return false
	}
	_, err := time.Parse(time.ANSIC, value)
	return err == nil
}

func hostLegacySaveHeader(line, program string) bool {
	tail, ok := strings.CutPrefix(line, "# Generated by "+program+" v")
	if !ok {
		return false
	}
	version, stamp, ok := strings.Cut(tail, " on ")
	parts := strings.Split(version, ".")
	if !ok || len(version) > 32 || len(parts) != 3 {
		return false
	}
	for _, part := range parts {
		value, err := strconv.ParseUint(part, 10, 32)
		if err != nil || strconv.FormatUint(value, 10) != part {
			return false
		}
	}
	return hostLegacySaveTime("# Completed on "+stamp, "# Completed on ")
}

func hostLegacySaveCounter(value string) bool {
	if len(value) < 5 || len(value) > 43 || value[0] != '[' || value[len(value)-1] != ']' {
		return false
	}
	parts := strings.Split(value[1:len(value)-1], ":")
	if len(parts) != 2 {
		return false
	}
	for _, part := range parts {
		count, err := strconv.ParseUint(part, 10, 64)
		if err != nil || strconv.FormatUint(count, 10) != part {
			return false
		}
	}
	return true
}

// Require every registered table exactly once, each complete header/table/
// ACCEPT-only builtin chain set/COMMIT/footer. Counters may vary with ordinary
// traffic; rules, custom chains, malformed framing and omitted tables refuse.
func hostLegacyEmptySave(raw []byte, program string, registered map[string]bool) (map[string][]string, error) {
	tables := map[string][]string{}
	if registered == nil {
		return nil, hostLegacyPolicyUnverified()
	}
	if len(raw) == 0 && len(registered) == 0 {
		return tables, nil
	}
	if len(raw) == 0 || len(raw) > 64*1024 || raw[len(raw)-1] != '\n' || bytes.IndexByte(raw, 0) >= 0 {
		return nil, hostLegacyPolicyUnverified()
	}
	lines := strings.Split(strings.TrimSuffix(string(raw), "\n"), "\n")
	for pos := 0; pos < len(lines); {
		if !hostLegacySaveHeader(lines[pos], program) || pos+1 >= len(lines) {
			return nil, hostLegacyPolicyUnverified()
		}
		pos++
		table, found := strings.CutPrefix(lines[pos], "*")
		if !found || !registered[table] || hostLegacyBuiltinChains(table) == nil || tables[table] != nil {
			return nil, hostLegacyPolicyUnverified()
		}
		wanted := map[string]bool{}
		for _, name := range hostLegacyBuiltinChains(table) {
			wanted[name] = true
		}
		order := []string{}
		pos++
		for pos < len(lines) && lines[pos] != "COMMIT" {
			parts := strings.Split(lines[pos], " ")
			if len(parts) != 3 || !strings.HasPrefix(parts[0], ":") || parts[1] != "ACCEPT" || !hostLegacySaveCounter(parts[2]) {
				return nil, hostLegacyPolicyUnverified()
			}
			name := strings.TrimPrefix(parts[0], ":")
			if !wanted[name] {
				return nil, hostLegacyPolicyUnverified()
			}
			delete(wanted, name)
			order = append(order, name)
			pos++
		}
		if len(wanted) != 0 || pos >= len(lines) || lines[pos] != "COMMIT" || pos+1 >= len(lines) ||
			!hostLegacySaveTime(lines[pos+1], "# Completed on ") {
			return nil, hostLegacyPolicyUnverified()
		}
		tables[table] = order
		pos += 2
	}
	if len(tables) != len(registered) {
		return nil, hostLegacyPolicyUnverified()
	}
	return tables, nil
}

// Preserve old -S raw digest material for registered tables: save and -S use
// the same libiptc builtin-chain order. A positively absent table has no active
// legacy policy; derive the canonical inert representation only after the
// complete successful proc/save proof, never from a missing file or command.
func hostLegacyInertPolicy(table string, tables map[string][]string) []byte {
	chains, loaded := tables[table]
	if !loaded {
		chains = hostLegacyBuiltinChains(table)
	}
	var out strings.Builder
	for _, chain := range chains {
		out.WriteString("-P " + chain + " ACCEPT\n")
	}
	return []byte(out.String())
}

func observeHostLegacyPacketPolicy() (hostLegacyPacketSnapshot, error) {
	// Debian save may try a userspace module loader after an init failure.
	// Suppress that fallback with a fixed, trusted failure executable.
	if verifyTrustedIPPath("/", "/usr/bin/false", 0) != nil {
		return hostLegacyPacketSnapshot{}, hostLegacyPolicyUnverified()
	}
	return observeHostLegacyPacketPolicyWith(readManagementProc, runReadOnlyHostNetfilter)
}

func observeHostLegacyPacketPolicyWith(readProc func(string, int64) ([]byte, error),
	readSave func(string, ...string) ([]byte, error)) (hostLegacyPacketSnapshot, error) {
	var result hostLegacyPacketSnapshot
	if readProc == nil || readSave == nil {
		return result, hostLegacyPolicyUnverified()
	}
	for family, name := range []string{"ip", "ip6"} {
		proc := "/proc/net/" + name + "_tables_names"
		before, err := readProc(proc, 256)
		if err != nil {
			return result, hostLegacyPolicyUnverified()
		}
		registered, err := hostLegacyRegisteredTables(before)
		if err != nil {
			return result, err
		}
		program := name + "tables-save"
		saved, err := readSave("/usr/sbin/"+name+"tables-legacy-save", "-M", "/usr/bin/false")
		if err != nil {
			return result, hostLegacyPolicyUnverified()
		}
		after, err := readProc(proc, 256)
		if err != nil || !bytes.Equal(before, after) {
			return result, hostLegacyPolicyUnverified()
		}
		tables, err := hostLegacyEmptySave(saved, program, registered)
		if err != nil {
			return result, err
		}
		result.raw[family] = hostLegacyInertPolicy("raw", tables)
		if family == 0 {
			result.nat4 = hostLegacyInertPolicy("nat", tables)
		}
	}
	// Reading a registered table may race a privileged unload/reload; Linux
	// can instantiate/autoload that table in GET_INFO. These bounded snapshots
	// do not claim atomicity or exclusion of such privileged mutations.
	return result, nil
}
