func hostLegacySaveFixture(program string, tables ...string) []byte {
	var out strings.Builder
	for _, table := range tables {
		out.WriteString("# Generated by " + program + " v1.8.11 on Sat Nov  7 02:00:00 2026\n*" + table + "\n")
		for _, chain := range hostLegacyBuiltinChains(table) {
			out.WriteString(":" + chain + " ACCEPT [123:4567]\n")
		}
		out.WriteString("COMMIT\n# Completed on Sat Nov  7 02:00:00 2026\n")
	}
	return []byte(out.String())
}

func TestHostLegacyCompleteEmptySaveGrammar(t *testing.T) {
	for _, program := range []string{"iptables-save", "ip6tables-save"} {
		t.Run(program, func(t *testing.T) {
			names := []byte("raw\nmangle\nnat\nfilter\nsecurity\n")
			registered, err := hostLegacyRegisteredTables(names)
			if err != nil {
				t.Fatal(err)
			}
			good := hostLegacySaveFixture(program, "raw", "mangle", "nat", "filter", "security")
			parsed, err := hostLegacyEmptySave(good, program, registered)
			if err != nil || len(parsed) != 5 {
				t.Fatalf("complete inert inventory rejected: %v", err)
			}
			if _, err := hostLegacyEmptySave(nil, program, map[string]bool{}); err != nil {
				t.Fatal("successfully observed no registered tables rejected:", err)
			}
			if _, err := hostLegacyEmptySave(nil, program, nil); err == nil {
				t.Fatal("missing registration evidence admitted")
			}
			max := bytes.ReplaceAll(good, []byte("[123:4567]"), []byte("[18446744073709551615:18446744073709551615]"))
			if _, err := hostLegacyEmptySave(max, program, registered); err != nil {
				t.Fatal("valid uint64 counter rejected:", err)
			}
			for _, tc := range []struct {
				name string
				raw  []byte
			}{
				{"empty dump omits registered tables", nil},
				{"missing table", hostLegacySaveFixture(program, "raw", "mangle", "nat", "filter")},
				{"duplicate table", append(append([]byte{}, good...), hostLegacySaveFixture(program, "raw")...)},
				{"unregistered table", append(append([]byte{}, good...), []byte("# Generated by "+program+" v1.8.11 on Sat Nov  7 02:00:00 2026\n*other\nCOMMIT\n# Completed on Sat Nov  7 02:00:00 2026\n")...)},
				{"wrong program", bytes.ReplaceAll(good, []byte(program+" v"), []byte(program+"-unknown v"))},
				{"legacy alias is not save program", bytes.ReplaceAll(good, []byte(program+" v"), []byte(strings.Replace(program, "-save", "-legacy-save", 1)+" v"))},
				{"unknown comment", append([]byte("# unknown\n"), good...)},
				{"missing header", good[bytes.IndexByte(good, '\n')+1:]},
				{"missing footer", good[:bytes.LastIndex(good, []byte("# Completed on "))]},
				{"missing commit", bytes.Replace(good, []byte("COMMIT\n"), nil, 1)},
				{"missing chain", bytes.Replace(good, []byte(":PREROUTING ACCEPT [123:4567]\n"), nil, 1)},
				{"duplicate chain", bytes.Replace(good, []byte(":PREROUTING ACCEPT [123:4567]\n"), []byte(":PREROUTING ACCEPT [123:4567]\n:PREROUTING ACCEPT [123:4567]\n"), 1)},
				{"custom chain", bytes.Replace(good, []byte("COMMIT\n"), []byte(":FOREIGN - [0:0]\nCOMMIT\n"), 1)},
				{"nonaccept builtin", bytes.Replace(good, []byte(" ACCEPT "), []byte(" DROP "), 1)},
				{"foreign rule", bytes.Replace(good, []byte("COMMIT\n"), []byte("-A OUTPUT -j NOTRACK\nCOMMIT\n"), 1)},
				{"overflow counter", bytes.Replace(good, []byte("[123:4567]"), []byte("[18446744073709551616:0]"), 1)},
				{"negative counter", bytes.Replace(good, []byte("[123:4567]"), []byte("[-1:0]"), 1)},
				{"noncanonical counter", bytes.Replace(good, []byte("[123:4567]"), []byte("[00:0]"), 1)},
				{"malformed header date", bytes.Replace(good, []byte("Sat Nov  7 02:00:00 2026"), []byte("not-a-time"), 1)},
				{"malformed header version", bytes.Replace(good, []byte("v1.8.11"), []byte("v01.8.11"), 1)},
				{"trailing line", append(append([]byte{}, good...), '\n')},
				{"incomplete final line", good[:len(good)-1]},
				{"nul", append(append([]byte{}, good...), 0, '\n')},
				{"oversized", bytes.Repeat([]byte("x"), 64*1024+1)},
			} {
				t.Run(tc.name, func(t *testing.T) {
					if _, err := hostLegacyEmptySave(tc.raw, program, registered); ErrorCode(err) != "foreign_legacy_policy_unverified" {
						t.Fatalf("incomplete/foreign policy admitted: %v", err)
					}
				})
			}
		})
	}
	for _, bad := range [][]byte{[]byte("nat"), []byte("nat\nnat\n"), []byte("future\n"), []byte("nat\n\n"), []byte("nat\x00\n"), bytes.Repeat([]byte("x"), 257)} {
		if _, err := hostLegacyRegisteredTables(bad); err == nil {
			t.Fatalf("invalid registered table list admitted: %q", bad)
		}
	}
}

func TestHostLegacyRawDigestRepresentationCompatibility(t *testing.T) {
	// Both former -S orders are accepted by the old journal contract. Save
	// enumerates the same builtin chains; preserve those bytes, not counters.
	for _, program := range []string{"iptables-save", "ip6tables-save"} {
		for _, reverse := range []bool{false, true} {
			saved := hostLegacySaveFixture(program, "raw", "nat")
			expected := []byte("-P PREROUTING ACCEPT\n-P OUTPUT ACCEPT\n")
			if reverse {
				saved = bytes.Replace(saved, []byte(":PREROUTING ACCEPT [123:4567]\n:OUTPUT ACCEPT [123:4567]\n"),
					[]byte(":OUTPUT ACCEPT [123:4567]\n:PREROUTING ACCEPT [123:4567]\n"), 1)
				expected = []byte("-P OUTPUT ACCEPT\n-P PREROUTING ACCEPT\n")
			}
			tables, err := hostLegacyEmptySave(saved, program, map[string]bool{"raw": true, "nat": true})
			if err != nil {
				t.Fatal(err)
			}
			actual := hostLegacyInertPolicy("raw", tables)
			if !bytes.Equal(expected, actual) || sha256Hex(expected) != sha256Hex(actual) || !strictEmptyLegacyRawPolicy(actual) {
				t.Fatalf("%s old -S raw material changed: %q -> %q", program, expected, actual)
			}
			if !strictEmptyLegacyNAT(hostLegacyInertPolicy("nat", tables)) {
				t.Fatal("derived NAT representation is not inert")
			}
		}
	}
}

func TestHostLegacyObservationRequiresSuccessfulStableCompleteEvidence(t *testing.T) {
	for _, mode := range []string{"registered empty", "all tables", "proc missing", "proc after fails", "proc changes",
		"unknown table", "save fails", "save truncates", "save omits", "IPv6 save fails", "IPv6 proc missing"} {
		t.Run(mode, func(t *testing.T) {
			procCalls, saveCalls := map[string]int{}, map[string]int{}
			readProc := func(path string, limit int64) ([]byte, error) {
				if limit != 256 || (path != "/proc/net/ip_tables_names" && path != "/proc/net/ip6_tables_names") {
					t.Fatalf("unexpected proc read %s/%d", path, limit)
				}
				procCalls[path]++
				if mode == "proc missing" || mode == "IPv6 proc missing" && strings.Contains(path, "ip6_") || mode == "proc after fails" && procCalls[path] == 2 {
					return nil, errors.New("proc unavailable")
				}
				if mode == "unknown table" {
					return []byte("future\n"), nil
				}
				if mode == "proc changes" && procCalls[path] == 2 {
					return []byte("raw\n"), nil
				}
				if mode == "registered empty" {
					return []byte{}, nil
				}
				return []byte("raw\nmangle\nnat\nfilter\nsecurity\n"), nil
			}
			readSave := func(binary string, args ...string) ([]byte, error) {
				if strings.Join(args, " ") != "-M /usr/bin/false" {
					t.Fatalf("unexpected save args: %v", args)
				}
				if binary != "/usr/sbin/iptables-legacy-save" && binary != "/usr/sbin/ip6tables-legacy-save" {
					t.Fatalf("unexpected save binary %s", binary)
				}
				saveCalls[binary]++
				if mode == "save fails" || mode == "IPv6 save fails" && strings.Contains(binary, "ip6tables") {
					return nil, errors.New("save unavailable")
				}
				if mode == "registered empty" {
					return []byte{}, nil
				}
				program := strings.Replace(strings.TrimPrefix(binary, "/usr/sbin/"), "-legacy-save", "-save", 1)
				saved := hostLegacySaveFixture(program, "raw", "mangle", "nat", "filter", "security")
				if mode == "save truncates" {
					saved = saved[:len(saved)-1]
				}
				if mode == "save omits" {
					saved = hostLegacySaveFixture(program, "raw")
				}
				return saved, nil
			}
			got, err := observeHostLegacyPacketPolicyWith(readProc, readSave)
			accept := mode == "registered empty" || mode == "all tables"
			if (err == nil) != accept {
				t.Fatalf("evidence accepted=%v want=%v: %v", err == nil, accept, err)
			}
			if accept {
				if len(procCalls) != 2 || len(saveCalls) != 2 {
					t.Fatalf("family evidence omitted: %v %v", procCalls, saveCalls)
				}
				for _, n := range procCalls {
					if n != 2 {
						t.Fatal("proc must bracket save exactly twice")
					}
				}
				for _, n := range saveCalls {
					if n != 1 {
						t.Fatal("duplicate or omitted backend save")
					}
				}
				if !strictEmptyLegacyRawPolicy(got.raw[0]) || !strictEmptyLegacyRawPolicy(got.raw[1]) || !strictEmptyLegacyNAT(got.nat4) {
					t.Fatal("invalid inert evidence")
				}
			}
		})
	}
	if _, err := observeHostLegacyPacketPolicyWith(nil, nil); err == nil {
		t.Fatal("missing observers admitted")
	}
}
